"""Publication-tier figures and the shared visual-identity style.

Two tiers share one visual language (see :mod:`cablexsec.plotting.style`):

- **Publication** (this package) — static, MATLAB-standard figures, each
  regenerated by code from a result object and annotating that result's
  limitations verbatim.
- **Exploratory** (:mod:`cablexsec.plotting.dashboard`) — a self-contained HTML
  *viewer* that renders result-object values + provenance and **computes no
  claimed number**.

The nine publication figures:

================================ ===================================
function                         renders
================================ ===================================
``plot_cross_section``           cable geometry, optionally σ-coloured
``plot_mkappa``                  M-κ loop vs experiment
``plot_mkappa_validation_suite`` benchmark grid
``plot_stress_distribution``     6-panel per-wire stress
``plot_stress_timeseries``       stacked κ / σ / δ* / tension
``plot_capacity_envelope``       capacity + usage factors
``plot_temperature_gradient``    radial T(r)
``plot_damage_split``            fatigue damage breakdown + polar
``plot_fretting_polar``          2D-Mindlin vs loxodromic (theorem)
================================ ===================================
"""

