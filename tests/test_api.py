def test_compute_mkappa_uses_papailiou_dissipation_engine() -> None:
    """Public moment calculation uses the physical-wire slip-front equations."""
    from cablexsec.cable_adapters import cable_to_mkappa_specs  # noqa: PLC0415
    from cablexsec.mechanics.papailiou import (  # noqa: PLC0415
        compute_mkappa_wire_slip_front,
        wire_slip_stress_cap,
    )

    cable = cx.load_cable(
        cx.inter_array_single_core_yaml_path(), geometry_override=None
    )  # has pretension_Pa → friction contact
    specs = cable_to_mkappa_specs(cable)
    onset = max(
        float(
            np.max(
                wire_slip_stress_cap(sp, 0.0)
                / (
                    sp.k_f
                    * sp.r_helix_m
                    * np.maximum(np.abs(np.cos(sp.phi_wires)), 1.0e-12)
                )
            )
        )
        for sp in specs
    )
    # Exercise actual sliding after changes to the support compliance, rather
    # than assuming a fixed curvature always exceeds the slip threshold.
    kappa = 3 * onset * np.sin(np.linspace(0.0, 6.0 * np.pi, 601))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        r = cx.compute_mkappa(cable, kappa, tension_N=0.0)
    ref = compute_mkappa_wire_slip_front(
        cable_to_mkappa_specs(cable), kappa, EI_min_Nm2=ei_min_slip(cable)
    )
    assert np.allclose(r.moment_Nm, ref.moment_Nm)
    assert r.W_diss_J_per_m == pytest.approx(ref.W_diss_J_per_m)
    assert r.W_diss_J_per_m > 0.0
    assert r.EI_min_Nm2 == pytest.approx(ei_min_slip(cable))
    # The Coulomb loop is a DIFFERENT engine (compute_mkappa does NOT use it):
    from dataclasses import replace

    # The auxiliary lumped law needs an explicit integration length for a
    # normal line load. One metre is a synthetic test input, not a cable fit.
    auxiliary = [
        replace(spec, friction_transfer_length_m=1.0)
        for spec in cable_to_mkappa_specs(cable, 0.0)
    ]
    loop = compute_mkappa_loop(auxiliary, kappa, EI_min_Nm2=ei_min_slip(cable))
    assert loop.W_diss_J_per_m != pytest.approx(r.W_diss_J_per_m, rel=0.05)
    assert r.provenance is not None
    assert any("Papailiou" in g or "BM2b" in g for g in r.provenance.gates)


def test_compute_mkappa_controls_change_the_physical_response() -> None:
    """Pressure changes slip response on a path that actually reaches slip."""
    cable = cx.load_cable(cx.menard2023_yaml_path(), geometry_override=None)
    kappa = 0.015 * np.sin(np.linspace(0.0, 4.0 * np.pi, 320))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        base = cx.compute_mkappa(cable, kappa)
        tensioned = cx.compute_mkappa(cable, kappa, tension_N=1.0e4)
        concentric = cx.load_cable(
            cx.inter_array_single_core_yaml_path(), geometry_override=None
        )
        from cablexsec.cable_adapters import armour_contact_pressure

        qp = cx.compute_mkappa(concentric, kappa, tension_N=1.0e6, contact_model="qp")
    assert base.W_diss_J_per_m > 0
    assert abs(np.ptp(tensioned.moment_Nm) / np.ptp(base.moment_Nm) - 1) > 0.05
    assert abs(tensioned.W_diss_J_per_m / base.W_diss_J_per_m - 1) > 0.05
    # Different contact pressures need not change moment while every wire
    # remains on the same elastic branch. Check pressure selection directly.
    assert np.isfinite(qp.moment_Nm).all()
    assert armour_contact_pressure(concentric, 1e6) != armour_contact_pressure(
        concentric, 1e6, contact_model="qp"
    )


def test_full_stick_response_is_rotation_invariant_with_uniform_pressure() -> None:
    """A pressure control need not change a response on the same elastic branch."""
    from cablexsec.cable_adapters import armour_contact_pressure

    cable = cx.load_cable(cx.inter_array_three_core_yaml_path(), geometry_override=None)
    kappa = 0.001 * np.sin(np.linspace(0.0, 4.0 * np.pi, 320))
    base = cx.compute_mkappa(cable, kappa)
    rotated = cx.compute_mkappa(cable, kappa, phi_bend=0.37)
    tensioned = cx.compute_mkappa(cable, kappa, tension_N=1e4)
    assert base.W_diss_J_per_m == 0.0
    np.testing.assert_allclose(
        rotated.moment_Nm, base.moment_Nm, rtol=1e-12, atol=1e-10
    )
    np.testing.assert_allclose(
        tensioned.moment_Nm, base.moment_Nm, rtol=1e-12, atol=1e-10
    )
    assert armour_contact_pressure(cable, 0.0) != armour_contact_pressure(cable, 1e4)


def test_fatigue_refreshes_contact_over_tension_history() -> None:
    """Dynamic tension affects contact unless a frozen reference is explicit."""
    cable = cx.load_cable(
        cx.inter_array_single_core_yaml_path(), geometry_override=None
    )
    cable = cable.model_copy(
        update={
            "layers": tuple(
                layer.model_copy(update={"pretension_Pa": 0.0})
                if layer.layer_type == "helical"
                else layer
                for layer in cable.layers
            )
        }
    )
    phase = np.linspace(0.0, 8.0 * np.pi, 320)
    kappa = 0.015 * np.sin(phase)
    tension = 5.0e5 * (1.0 + np.sin(0.5 * phase))
    dynamic = cx.compute_fatigue(cable, kappa, np.zeros_like(kappa), tension_N=tension)
    frozen = cx.compute_fatigue(
        cable,
        kappa,
        np.zeros_like(kappa),
        tension_N=tension,
        contact_tension_N=0.0,
    )
    assert any(
        not np.array_equal(
            dynamic.D_total_per_wire[name], frozen.D_total_per_wire[name]
        )
        for name in dynamic.D_total_per_wire
    )


