def test_compute_thermal_warns_above_xlpe_limit() -> None:
    tb = _tb880()
    # Heavy overload current drives the conductor past the 90 degC XLPE limit.
    with warnings.catch_warnings(record=True) as w:
        warnings.simplefilter("always")
        res = cx.compute_thermal(tb, 4000.0, 1200e-6, n_cores=1)
    if res.T_conductor_C > 90.0:
        assert any(issubclass(x.category, cx.ExtrapolationWarning) for x in w)


